"""Synthetic starter data for the first LoRA smoke run.

Every row is produced by the rules in this file, from a fixed seed. The answers are
computed by Python. No person wrote them and nothing was collected from anyone. The
data exists so that the training pipeline can be exercised end to end without any
user-supplied dataset. It says nothing about any domain, and every file and manifest
it writes says so in its label.

The notebook regenerates these files and compares their SHA-256 with the pins in the
job file. A mismatch is refused, so the same job always trains on the same bytes.
"""

from __future__ import annotations

import hashlib
import json
import random
from pathlib import Path

GENERATOR = "fabric/training/synthetic.py"
GENERATOR_VERSION = "1"
SEED = 20261015
LABEL = "SYNTHETIC DEMONSTRATION DATA: generated by rules, not collected, not domain knowledge"
INSTRUCTION_MARKER = "### Instruction:\n"
RESPONSE_MARKER = "### Response:\n"

#: Split name -> row count. ``synthetic-regression`` is a family that never appears in
#: training, so it measures damage to unrelated behaviour.
SPLIT_SIZES = {"train": 2000, "validation": 300, "synthetic-regression": 40}
FILES = {
    "train": "train.jsonl",
    "validation": "validation.jsonl",
    "synthetic-regression": "synthetic-regression.jsonl",
}

_SYLLABLES = ["ka", "lo", "mi", "ru", "sen", "ta", "vo", "pix", "dra", "nel", "gu", "shi",
              "bo", "fa", "wen", "ze", "ili", "tor", "mab", "qu"]
_THINGS = {
    "grass": "green", "snow": "white", "coal": "black", "the sky": "blue",
    "a banana": "yellow", "a rose": "red", "a carrot": "orange", "an egg shell": "white",
}
_PHRASINGS = [
    "What colour is {thing}?",
    "Name the colour of {thing}.",
    "Tell me the usual colour of {thing}.",
    "What colour do people usually see on {thing}?",
    "Describe the colour of {thing} in one word.",
]
_TRAINING_FAMILIES = ("addition", "reverse_words", "letter_count", "uppercase", "vowel_count", "sort_numbers")


class SyntheticError(RuntimeError):
    pass


def _word(rng: random.Random) -> str:
    return "".join(rng.choice(_SYLLABLES) for _ in range(rng.randint(2, 3)))


def _example(rng: random.Random, family: str) -> tuple[str, str]:
    """Return (instruction, response) for one row of ``family``. Answers are computed here."""
    if family == "addition":
        a, b = rng.randint(1, 99), rng.randint(1, 99)
        return f"What is {a} plus {b}?", f"{a} plus {b} is {a + b}."
    if family == "reverse_words":
        words = [_word(rng) for _ in range(3)]
        return (f"Reverse the order of these words: {' '.join(words)}.",
                f"The reversed order is: {' '.join(reversed(words))}.")
    if family == "letter_count":
        word = _word(rng)
        return f"How many letters are in the word {word}?", f"The word {word} has {len(word)} letters."
    if family == "uppercase":
        word = _word(rng)
        return f"Write the word {word} in capital letters.", word.upper()
    if family == "vowel_count":
        word = _word(rng)
        count = sum(ch in "aeiou" for ch in word)
        return f"How many vowels are in the word {word}?", f"The word {word} has {count} vowels."
    if family == "sort_numbers":
        numbers = rng.sample(range(1, 100), 4)
        return (f"Sort these numbers from smallest to largest: {', '.join(map(str, numbers))}.",
                ", ".join(map(str, sorted(numbers))) + ".")
    if family == "colour_facts":
        thing = rng.choice(sorted(_THINGS))
        phrasing = rng.choice(_PHRASINGS)
        return phrasing.format(thing=thing), f"{thing[:1].upper() + thing[1:]} is {_THINGS[thing]}."
    raise SyntheticError(f"unknown family {family!r}")


def _text(instruction: str, response: str) -> str:
    return f"{INSTRUCTION_MARKER}{instruction}\n\n{RESPONSE_MARKER}{response}"


def build_splits() -> dict:
    """Generate every split. Deterministic: the same code always yields the same rows.

    Splits are disjoint by text: a validation or regression row never repeats a training
    row, so measured gains cannot come from memorised answers.
    """
    seen: set[str] = set()
    splits: dict[str, list[dict]] = {}
    for split, size in SPLIT_SIZES.items():
        rng = random.Random(f"{SEED}:{GENERATOR_VERSION}:{split}")
        families = ("colour_facts",) if split == "synthetic-regression" else _TRAINING_FAMILIES
        rows: list[dict] = []
        attempts = 0
        while len(rows) < size:
            attempts += 1
            if attempts > size * 200:
                raise SyntheticError(f"could not generate {size} unseen rows for {split!r}")
            family = families[len(rows) % len(families)]
            text = _text(*_example(rng, family))
            if text in seen:
                continue
            seen.add(text)
            rows.append({"id": f"{split}-{len(rows):05d}", "family": family, "label": LABEL,
                         "synthetic": True, "text": text})
        splits[split] = rows
    return splits


def encode(rows: list[dict]) -> bytes:
    """One canonical JSON object per line. Key order and escaping are fixed."""
    return b"".join(
        (json.dumps(row, sort_keys=True, ensure_ascii=True, separators=(",", ":")) + "\n").encode("ascii")
        for row in rows
    )


def pins() -> dict:
    """SHA-256, size and count of every split's file, without writing anything."""
    out = {}
    for split, rows in build_splits().items():
        data = encode(rows)
        out[split] = {"file": FILES[split], "sha256": hashlib.sha256(data).hexdigest(),
                      "bytes": len(data), "examples": len(rows)}
    return out


def write_dataset(directory: str | Path) -> dict:
    """Write the split files and a provenance manifest, and return the manifest."""
    out = Path(directory)
    out.mkdir(parents=True, exist_ok=True)
    files = {}
    for split, rows in build_splits().items():
        data = encode(rows)
        (out / FILES[split]).write_bytes(data)
        files[split] = {"file": FILES[split], "sha256": hashlib.sha256(data).hexdigest(),
                        "bytes": len(data), "examples": len(rows),
                        "families": sorted({row["family"] for row in rows})}
    manifest = {
        "label": LABEL,
        "notice": "Generated by fabric/training/synthetic.py. Not collected data, not user data, "
                  "not domain knowledge. For pipeline testing only.",
        "generator": GENERATOR,
        "generatorVersion": GENERATOR_VERSION,
        "seed": SEED,
        "markers": {"instruction": INSTRUCTION_MARKER, "response": RESPONSE_MARKER},
        "files": files,
    }
    manifest["digest"] = hashlib.sha256(
        json.dumps(files, sort_keys=True, separators=(",", ":")).encode("utf-8")
    ).hexdigest()
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return manifest
